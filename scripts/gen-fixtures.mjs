#!/usr/bin/env node
// Generates the web app's data fixtures by calling the REAL Python engine.
//
// The deployed web app cannot spawn Python, and reimplementing the solver in TypeScript would
// create a second code path — the exact thing the narrow waist forbids. So the web renders
// output the real engine produced, and `check-fixtures.mjs` fails the build if the committed
// fixtures ever drift from what the engine currently computes.
//
//   node scripts/gen-fixtures.mjs          write the fixtures
//   node scripts/gen-fixtures.mjs --check  fail if they are stale

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENGINE_SRC = join(ROOT, 'services', 'engine', 'src')
const OUT = join(ROOT, 'apps', 'web', 'fixtures')
const CHECK_ONLY = process.argv.includes('--check')

const INSTANCES = [
  { id: 'overnight-tariff', file: 'examples/overnight-tariff.json' },
  { id: 'overnight-conflict', file: 'examples/overnight-conflict.json' },
]

function callEngine(op, input) {
  const stdout = execFileSync('python', ['-m', 'dispatch_envelope'], {
    cwd: ENGINE_SRC,
    input: JSON.stringify({ op, input: toEngineInput(input) }),
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  })
  const response = JSON.parse(stdout)
  if (!response.ok) {
    throw new Error(`engine op "${op}" failed: ${response.error?.code} ${response.error?.message}`)
  }
  return response.value
}

/**
 * camelCase (the public instance format users write) to snake_case (what the engine speaks).
 *
 * This mirrors `toEngineInput` in packages/cli/src/bootstrap.ts. It is duplicated rather than
 * imported because this is a build script that must run before anything is compiled, and a
 * build script that cannot run is a build script nobody runs.
 */
function toEngineInput(instance) {
  const site = {
    slots: instance.site.slots,
    slot_minutes: instance.site.slotMinutes,
    site_limit_kw: instance.site.siteLimitKw,
  }
  if (instance.site.exportLimitKw !== undefined) site.export_limit_kw = instance.site.exportLimitKw

  const loads = instance.loads.map((load) => {
    const row = {
      id: load.id,
      power_kw: load.powerKw,
      earliest_slot: load.earliestSlot,
      latest_slot: load.latestSlot,
      min_slots: load.minSlots,
      max_slots: load.maxSlots ?? load.minSlots,
      mandatory: load.mandatory ?? false,
    }
    if (load.name !== undefined) row.name = load.name
    return row
  })

  const payload = { site, loads }
  if (instance.tariff !== undefined) {
    payload.tariff = {
      prices_cents: [...instance.tariff.pricesCents],
      ...(instance.tariff.currency === undefined ? {} : { currency: instance.tariff.currency }),
    }
  }
  if (instance.optimise !== undefined) payload.optimise = instance.optimise
  return payload
}

mkdirSync(OUT, { recursive: true })

let stale = 0
const summary = []

for (const instance of INSTANCES) {
  const input = JSON.parse(readFileSync(join(ROOT, instance.file), 'utf8'))
  const envelope = callEngine('propagate_envelope', input)
  const plan = callEngine('dispatch', input)
  const proof = callEngine('prove_infeasible', input)

  const fixture = {
    $comment:
      'Generated by scripts/gen-fixtures.mjs from the real Python engine. Do not edit by hand; ' +
      'run the generator or check:fixtures will fail.',
    id: instance.id,
    source: instance.file,
    site: input.site,
    tariff: input.tariff ?? null,
    loads: input.loads,
    envelope,
    plan,
    proof,
  }

  // prettier-canonical: no trailing newline. Emitting prettier's own shape keeps
  // `format:check` and this gate in agreement.
  function canonical(value) {
    return JSON.stringify(value, null, 2).replace(/\s+$/, '')
  }
  // would fail on formatting while the data was identical. Only the DATA is load-bearing.
  // Compared as parsed values, not bytes: only the DATA is load-bearing, and a formatter
  // disagreement must never be able to fail a build about solver behaviour.
  const target = join(OUT, `${instance.id}.json`)

  if (CHECK_ONLY) {
    let existing = null
    try {
      existing = JSON.parse(readFileSync(target, 'utf8'))
    } catch {
      existing = null
    }
    if (existing === null) {
      stale += 1
      console.error(`  MISSING  ${instance.id}.json has not been generated`)
    } else if (JSON.stringify(existing) !== JSON.stringify(fixture)) {
      stale += 1
      console.error(`  STALE    ${instance.id}.json does not match the current engine output`)
    } else {
      console.log(`  ok       ${instance.id}.json`)
    }
  } else {
    writeFileSync(target, canonical(fixture), 'utf8')
    summary.push(
      `  wrote  ${instance.id}.json  (plan ${plan.feasible ? 'feasible' : 'refused'}, proof ` +
        `${proof.infeasible ? 'infeasible' : 'feasible'})`,
    )
  }
}

if (CHECK_ONLY) {
  if (stale > 0) {
    console.error('')
    console.error('check:fixtures FAILED — the web fixtures no longer match the engine.')
    console.error('fix: run "npm run gen:fixtures" and commit the result')
    process.exit(1)
  }
  console.log('check:fixtures — clean (web fixtures match the engine)')
} else {
  for (const line of summary) console.log(line)
}
